function genEntries(prefix: string): AbaqueEntry[] {
  const devTypes: Array<'Formulaire' | 'Report' | 'Enhancement' | 'Programme'> = ['Formulaire', 'Report', 'Enhancement', 'Programme'];
  const complexites: Array<'Simple' | 'Moyen' | 'Complexe' | 'Très Complexe'> = ['Simple', 'Moyen', 'Complexe', 'Très Complexe'];
  const priorites: Array<0 | 1 | 2 | 3> = [0, 1, 2, 3];

  // Baseline days per complexite
  const baseDays: Record<string, number> = { Simple: 1, Moyen: 3, Complexe: 6, 'Très Complexe': 12 };
  // devType multiplier
  const devMul: Record<string, number> = { Formulaire: 1, Report: 0.8, Enhancement: 1.2, Programme: 1.5 };
  // priorite offset (lower number = highest priority = tighter tolerance)
  const prioOff: Record<number, number> = { 0: 1, 1: 0.5, 2: 0, 3: 0 };

  const entries: AbaqueEntry[] = [];
  let idx = 1;
  for (const dt of devTypes) {
    for (const cx of complexites) {
      for (const pr of priorites) {
        // Skip some combos to leave gaps (~60% fill)
        if ((idx + pr) % 5 === 0) { idx++; continue; }
        const std = Math.max(1, Math.round(baseDays[cx] * devMul[dt] + prioOff[pr]));
        const max = std + Math.max(1, Math.round(std * 0.5));
        const note = cx === 'Très Complexe' ? 'Revue architecturale obligatoire' : undefined;
        entries.push({ id: `${prefix}-e${idx}`, devType: dt, complexite: cx, priorite: pr, standardDays: std, maxDays: max, notes: note });
        idx++;
      }
    }
  }
  return entries;
}

